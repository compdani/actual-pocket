// timestamps.json

// Every entry is either obviously valid or obviously invalid. Zone-less
// date-times are deliberately excluded: JavaScript reads those in the local
// time zone, which would make the fixture depend on the machine that generated
// it.
const malformedTimestamps = [
  '',
  ' ',
  '0',
  'invalid',
  '2020-01-01T00:00:00.000Z',
  '2020-01-01T00:00:00.000Z-0000-node-extra',
  '2020-01-01-0000-node-extra',
  '1969-12-31T23:59:59.999Z-0000-0123456789ABCDEF',
  '2020-13-01T00:00:00.000Z-0000-0123456789ABCDEF',
  '2020-00-10T00:00:00.000Z-0000-0123456789ABCDEF',
  '2020-01-32T00:00:00.000Z-0000-0123456789ABCDEF',
  '2020-01-01T25:00:00.000Z-0000-0123456789ABCDEF',
  '2020-01-01T00:60:00.000Z-0000-0123456789ABCDEF',
  '2020-01-01T00:00:60.000Z-0000-0123456789ABCDEF',
  // Hour 24 is only valid when everything after it is zero.
  '2020-01-01T24:00:01.000Z-0000-0123456789ABCDEF',
  '2020-01-01T24:00:00.100Z-0000-0123456789ABCDEF',
  // A "-" offset would add a sixth dash-separated part.
  '2020-01-01T00:00:00.123-05:30-0001-0123456789ABCDEF',
  // So would a negative counter.
  '2020-01-01T00:00:00.000Z--1-0123456789ABCDEF',
  '2020-01-01T00:00:00.000Z-10000-0123456789ABCDEF',
  '2020-01-01T00:00:00.000Z-zz-0123456789ABCDEF',
  '2020-01-01T00:00:00.000Z-0000-0123456789ABCDEFG',
  '2020-01-01T00:00:00.000Z-0000-😀😀😀😀😀😀😀😀😀',
  '2020-01-01T00:00:00.000+00-0000-0123456789ABCDEF',
  '10000-01-01T00:00:00.000Z-FFFF-FFFFFFFFFFFFFFFF',
];

const trickyValidTimestamps = [
  // Zero and maximum.
  '1970-01-01T00:00:00.000Z-0000-0000000000000000',
  '9999-12-31T23:59:59.999Z-FFFF-FFFFFFFFFFFFFFFF',
  // A client-shaped value.
  '2015-04-24T22:23:42.123Z-1000-0123456789ABCDEF',
  // Short counter and node are accepted.
  '2020-01-01T00:00:00.000Z-0-0',
  // No fractional seconds.
  '2020-01-01T00:00:00Z-0001-0123456789ABCDEF',
  // More than three fractional digits (truncated to milliseconds).
  '2020-01-01T00:00:00.123456Z-0001-0123456789ABCDEF',
  // Lowercase zone marker and lowercase separator.
  '2020-01-01t00:00:00.123z-0001-0123456789ABCDEF',
  // Explicit numeric offset, with and without the colon.
  '2020-01-01T00:00:00.123+02:00-0001-0123456789ABCDEF',
  '2020-01-01T00:00:00.123+0530-0001-0123456789ABCDEF',
  // A space instead of "T".
  '2020-01-01 00:00:00.000Z-0001-0123456789ABCDEF',
  // Sunday, February 30th: JavaScript normalises the overflowing day.
  '2020-02-30T00:00:00.000Z-0000-0123456789ABCDEF',
  // 24:00:00.000 rolls over to the next day.
  '2020-01-01T24:00:00.000Z-0000-0123456789ABCDEF',
  // parseInt() tolerates a leading sign, whitespace and a 0x prefix.
  '2020-01-01T00:00:00.000Z- 1f-0123456789ABCDEF',
  '2020-01-01T00:00:00.000Z-0x1f-0123456789ABCDEF',
  // parseInt() stops at the first invalid digit.
  '2020-01-01T00:00:00.000Z-1g-0123456789ABCDEF',
  // Eight emoji are 16 UTF-16 code units, which is still within the limit.
  '2020-01-01T00:00:00.000Z-0000-😀😀😀😀😀😀😀😀',
  // A date-only date part is valid (and parsed as UTC, like JavaScript).
  '2020-01-01-0000-0123456789ABCDEF',
];

function generateTimestamps() {
  const rng = mulberry32(0x2222);
  const inputs = [...malformedTimestamps, ...trickyValidTimestamps];

  const minMillis = Date.parse('1970-01-01T00:00:00.000Z');
  const maxMillis = Date.parse('9999-12-31T23:59:59.999Z');

  while (inputs.length < 200) {
    const millis = randomInt(rng, minMillis, maxMillis);
    const counter = randomInt(rng, 0, 0xffff);
    inputs.push(makeTimestamp(millis, counter, hex(rng, 16)));
  }

  const cases = inputs.map(input => {
    const parsed = Timestamp.parse(input);
    if (!parsed) {
      return { input, ok: false };
    }
    return {
      input,
      ok: true,
      millis: parsed.millis(),
      str: parsed.toString(),
      hash: parsed.hash(),
    };
  });

  writeJSON('timestamps.json', {
    note: 'Generated by scripts/gen-crdt-fixtures.mjs from @actual-app/crdt; do not edit.',
    cases,
  });
}

// ------------------------------------------------------------------
// merkle-*.json

/**
 * Builds `count` timestamps across the years, with deliberate coverage of the
 * tricky merkle cases:
 *   - duplicates (a repeated timestamp cancels its hash back to 0),
 *   - many timestamps inside one minute (long shared prefixes),
 *   - timestamps spread across decades (wide branching).
 */
function makeSequence(count, seed) {
  const rng = mulberry32(seed);
  const minMillis = Date.parse('2005-01-01T00:00:00.000Z');
  const maxMillis = Date.parse('2026-01-01T00:00:00.000Z');

  const timestamps = [];
  const push = (millis, counter, node) => {
    timestamps.push(makeTimestamp(millis, counter, node));
  };

  // A shared minute with different counter values, then a duplicate pair that
  // XORs a whole subtree back to a zero hash.
  const sharedMinute = Date.parse('2021-06-15T12:00:00.000Z');
  push(sharedMinute + 1, 0, 'AAAAAAAAAAAAAAAA');
  push(sharedMinute + 1, 1, 'AAAAAAAAAAAAAAAA');
  push(sharedMinute + 2, 2, 'AAAAAAAAAAAAAAAA');
  const cancelled = makeTimestamp(sharedMinute + 3, 3, 'BBBBBBBBBBBBBBBB');
  push(sharedMinute + 3, 3, 'BBBBBBBBBBBBBBBB');
  push(sharedMinute + 3, 3, 'BBBBBBBBBBBBBBBB');

  while (timestamps.length < count) {
    // Every 37th value repeats the previous one, exercising the "hash became
    // zero" branch of prune().
    if (timestamps.length % 37 === 0 && timestamps.length > 0) {
      timestamps.push(timestamps[timestamps.length - 1]);
      continue;
    }
    const millis = randomInt(rng, minMillis, maxMillis);
    push(millis, randomInt(rng, 0, 0xffff), hex(rng, 16));
  }

  return { timestamps: timestamps.slice(0, count), cancelled };
}

/**
 * Inserts every timestamp in order, recording JSON.stringify(trie) and
 * JSON.stringify(prune(trie)) at the requested checkpoints.
 */
function buildMerkleFixture(count, seed, checkpoints) {
  const { timestamps } = makeSequence(count, seed);

  // The server starts from {} when the group database has no merkle row yet.
  let trie = {};
  const snapshots = [];
  const wanted = new Set(checkpoints);

  for (let i = 0; i < timestamps.length; i++) {
    const parsed = Timestamp.parse(timestamps[i]);
    if (!parsed) {
      throw new Error(`generated an invalid timestamp: ${timestamps[i]}`);
    }
    trie = merkle.insert(trie, parsed);

    if (wanted.has(i + 1)) {
      snapshots.push({
        inserted: i + 1,
        trie: JSON.stringify(trie),
        pruned: JSON.stringify(merkle.prune(trie)),
      });
    }
  }

  return { count, timestamps, snapshots };
}

function generateMerkle() {
  const fixtures = [
    { name: 'merkle-1.json', count: 1, seed: 0x3001, checkpoints: [1] },
    {
      name: 'merkle-10.json',
      count: 10,
      seed: 0x3010,
      checkpoints: [2, 5, 10],
    },
    {
      name: 'merkle-1000.json',
      count: 1000,
      seed: 0x3e8,
      checkpoints: [10, 100, 999, 1000],
    },
    {
      name: 'merkle-10000.json',
      count: 10000,
      seed: 0x2710,
      checkpoints: [10, 1000, 10000],
    },
  ];

  for (const fixture of fixtures) {
    const data = buildMerkleFixture(
      fixture.count,
      fixture.seed,
      fixture.checkpoints,
    );
    writeJSON(fixture.name, {
      note: 'Generated by scripts/gen-crdt-fixtures.mjs from @actual-app/crdt; do not edit.',
      ...data,
    });
  }
}

mkdirSync(outDir, { recursive: true });
generateMurmur();
generateTimestamps();
generateMerkle();
