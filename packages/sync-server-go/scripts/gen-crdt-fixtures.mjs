#!/usr/bin/env node
// Generates the CRDT golden fixtures used by the Go tests in internal/crdt.
//
// The JS implementation in packages/crdt is the reference: every value written
// here comes from it, so a Go mismatch means a porting bug, not a stale test.
//
// Usage (from the repo root):
//   corepack pnpm --filter @actual-app/crdt run build:node
//   node packages/sync-server-go/scripts/gen-crdt-fixtures.mjs
//
// `make fixtures` does both.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', 'testdata', 'crdt');

// @actual-app/crdt's entry point is TypeScript, which plain node cannot load.
// Use the built bundle from `pnpm --filter @actual-app/crdt run build:node`.
const crdtEntry = join(here, '..', '..', 'crdt', 'dist', 'index.js');

let crdt;
try {
  crdt = await import(crdtEntry);
} catch (error) {
  console.error(`Could not load ${crdtEntry}:`);
  console.error(error.message);
  console.error(
    '\nBuild it first: corepack pnpm --filter @actual-app/crdt run build:node',
  );
  process.exit(1);
}

const { merkle, Timestamp } = crdt;
const { default: murmurhash } = await import('murmurhash');

// Deterministic PRNG so regenerating the fixtures on another machine produces
// the same files.
function mulberry32(seed) {
  let a = seed;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function randomInt(rng, min, max) {
  return min + Math.floor(rng() * (max - min + 1));
}

function randomAscii(rng, length) {
  let out = '';
  for (let i = 0; i < length; i++) {
    // Printable ASCII, including spaces and punctuation.
    out += String.fromCharCode(randomInt(rng, 0x20, 0x7e));
  }
  return out;
}

function hex(rng, length) {
  let out = '';
  for (let i = 0; i < length; i++) {
    out += randomInt(rng, 0, 15).toString(16).toUpperCase();
  }
  return out;
}

function padCounter(counter) {
  return ('0000' + counter.toString(16).toUpperCase()).slice(-4);
}

function padNode(node) {
  return ('0000000000000000' + node).slice(-16);
}

/** Builds a timestamp string exactly like the client does. */
function makeTimestamp(millis, counter, node) {
  return `${new Date(millis).toISOString()}-${padCounter(counter)}-${padNode(node)}`;
}

function writeJSON(name, value) {
  // Compact, like the strings the Go tests compare. The fixtures are machine
  // generated, so they are excluded from the repo formatter.
  writeFileSync(join(outDir, name), JSON.stringify(value) + '\n');
  console.log(`wrote ${name}`);
}

// ------------------------------------------------------------------
// murmur.json

function generateMurmur() {
  const rng = mulberry32(0x1111);
  const cases = [];

  // A few deliberate shapes first: empty input, short inputs, block edges.
  for (const input of [
    '',
    'a',
    'ab',
    'abc',
    'abcd',
    'abcde',
    'x'.repeat(1023),
    'x'.repeat(1024),
    'x'.repeat(1025),
  ]) {
    cases.push({ input, hash: murmurhash.v3(input) });
  }

  while (cases.length < 200) {
    const input = randomAscii(rng, randomInt(rng, 0, 200));
    cases.push({ input, hash: murmurhash.v3(input) });
  }

  writeJSON('murmur.json', {
    note: 'Generated by scripts/gen-crdt-fixtures.mjs from murmurhash@2 v3(); do not edit.',
    cases,
  });
}

